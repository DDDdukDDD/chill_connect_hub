const DISTRICT_OF: Record<string, string> = Object.fromEntries(
  Object.entries(BY_DISTRICT).flatMap(([district, subs]) => subs.map((sub) => [sub, district]))
);

/** The Bangkok district a sub-district belongs to; any other name comes back unchanged */
export function bangkokDistrictOf(name: string): string {
  return DISTRICT_OF[name.replace(/^แขวง\s*/, '').trim()] ?? name;
}
